-- Tâche 1 : langues et réglages
local M = dofile("test/mock.lua")
local function load()
    dofile("HookAndHarvest/Locales/enUS.lua"); dofile("HookAndHarvest/Locales/frFR.lua"); dofile("HookAndHarvest/Locales/esES.lua")
    dofile("HookAndHarvest/Core.lua")
end
M.locale = "esMX"; M.reset(); load()
ok(HH.LANG == "es", "esMX -> es")
ok(HH.L.prompt_cast == "Lanzar el sedal", "texte espagnol")
ok(HH.L.__absent_test == "__absent_test", "clé absente -> la clé elle-même")
M.locale = "deDE"; M.reset(); load()
ok(HH.LANG == "en" and HH.L.prompt_cast == "Cast line", "autre langue -> anglais")
M.locale = "frFR"; M.reset(); load()
ok(HH.L.prompt_reel == "Ferrer !", "texte français")
HH.Config:Init()
ok(HH.Config:Get("historySize") == 100 and HH.Config:Get("key") == "F", "défauts posés")
ok(HookAndHarvestDB.version == 1, "version 1")
HookAndHarvestDB = { key = "G" }; HH.Config:Init()
ok(HH.Config:Get("key") == "G" and HH.Config:Get("rpChance") == 20, "réglage existant gardé, manquant ajouté")
ok(type(HH.Config:Char().totals) == "table" and type(HH.Config:Char().history) == "table", "sous-table personnage")
ok(HookAndHarvestDB.chars["Ghosti-Forever"] == HH.Config:Char(), "clé Nom-Royaume")
